"""Audit Generated Dataset for Phase 3 Physical & Mathematical Integrity.

Runs comprehensive sanity, physical, and mathematical checks on the Parquet database
generated by runner_sc_v21_qssa.py before launching neural network training.

Checks performed:
1. File integrity, total trajectory count, step count, and trajectory yield/success rate.
2. Trajectory termination reason distribution (guards against premature equilibrium truncation
   and distinguishes step truncation 'max_steps' from physical timeout 'unignited_timeout').
3. Exact QSSA algebraic closure check: verifies BOTH absolute residual (< 1e-10)
   AND species-by-species relative error (< 1e-6) on active species.
4. Pressure unit & range validation (checks P in [0.05, 500] atm, flags accidental Pa values).
5. Physical stratification & metadata audit (stratum_name, Z_dil).
6. Cold oxidation baseline check (verifies initial radicals are exactly 0).
"""

from __future__ import annotations

import argparse
import gc
import json
from pathlib import Path
import sys
import numpy as np
import pandas as pd


def audit_database(
    database_dir: str | Path,
    max_check_rows: int = 20000,
    check_all_rows: bool = True,
    relative_floor: float = 1e-40,
    negative_tolerance: float = 1e-40,
    min_success_rate: float = 90.0,
    max_pressure: float = 1000.0,
):
    db_path = Path(database_dir).resolve()
    print("=" * 78)
    print(f"AUDITING DATASET: {db_path}")
    print("=" * 78)

    if not db_path.exists():
        raise FileNotFoundError(f"Database directory not found: {db_path}")

    has_error = False

    if not np.isfinite(relative_floor) or relative_floor <= 0.0:
        raise ValueError("relative_floor must be finite and positive")
    if not np.isfinite(negative_tolerance) or negative_tolerance < 0.0:
        raise ValueError("negative_tolerance must be finite and non-negative")

    # 1. Find all parquet files
    parquet_files = sorted(db_path.glob("**/*.parquet"))
    if not parquet_files:
        raise FileNotFoundError(f"No parquet files found in {db_path}")
    n_parts = len(parquet_files)
    print(f"Found {n_parts} parquet part files.")

    # 2. Inspect summary and metadata if available
    summary_file = db_path / "database_summary.json"
    if summary_file.exists():
        try:
            with open(summary_file, "r", encoding="utf-8") as f:
                s_data = json.load(f)
            if isinstance(s_data, list):
                s_data = s_data[0]
            inp_s = s_data.get("total_input_samples", s_data.get("input_samples", "N/A"))
            succ_s = s_data.get("success_trajectories", s_data.get("success", "N/A"))
            fail_s = s_data.get("failed_trajectories", s_data.get("failed", 0))

            if (
                isinstance(inp_s, (int, float))
                and isinstance(succ_s, (int, float))
                and inp_s > 0
            ):
                succ_rate = (succ_s / inp_s) * 100.0
                print(
                    f"Database Summary: input={inp_s:,}, success={succ_s:,}, "
                    f"failed={fail_s:,} (success rate: {succ_rate:.2f}%)"
                )
                if succ_rate >= min_success_rate:
                    print(
                        f"  [PASS] High trajectory yield ({succ_rate:.2f}% >= {min_success_rate:.1f}%)."
                    )
                    if fail_s > 0:
                        print(
                            f"         ({fail_s:,} extreme/stiff boundary samples safely rejected "
                            f"by solver filters; none written to database)"
                        )
                else:
                    print(
                        f"  [FAIL] Summary trajectory success rate ({succ_rate:.2f}%) "
                        f"is below {min_success_rate:.1f}% threshold!"
                    )
                    has_error = True
            else:
                print(f"Database Summary: input={inp_s}, success={succ_s}, failed={fail_s}")
        except Exception as exc:
            print(f"  [WARN] Failed to read database_summary.json: {exc}")

    meta_files = sorted(db_path.glob("**/metadata.json"))
    for mf in meta_files:
        try:
            with open(mf, "r", encoding="utf-8") as f:
                m_data = json.load(f)
            if isinstance(m_data, list):
                m_data = m_data[0]
            m_mech = m_data.get("mechanism_name", mf.parent.name)
            m_succ = m_data.get("success", 0)
            m_fail = m_data.get("failed", 0)
            m_rows = m_data.get("training_rows", 0)
            m_total = m_succ + m_fail
            m_rate = (m_succ / m_total * 100.0) if m_total > 0 else 0.0

            print(
                f"Mechanism [{m_mech}]: success={m_succ:,}, failed={m_fail:,}, "
                f"rows={m_rows:,} (yield: {m_rate:.2f}%)"
            )
            if m_rate < min_success_rate:
                print(
                    f"  [FAIL] Mechanism [{m_mech}] success rate ({m_rate:.2f}%) "
                    f"is below {min_success_rate:.1f}% threshold!"
                )
                has_error = True
            else:
                print(
                    f"  [PASS] Mechanism [{m_mech}] completed with high trajectory yield ({m_rate:.2f}%)."
                )
        except Exception as exc:
            print(f"  [WARN] Failed to read {mf}: {exc}")

    # 3. Streaming on-the-fly audit across parquet files
    total_rows = 0
    trajectories_seen = set()
    termination_counts = {}
    stratum_counts = {}
    p_min_overall, p_max_overall = float("inf"), float("-inf")
    negative_state_count = 0

    # Cold oxidation radical check accumulator
    cold_t0_count = 0
    cold_t0_max_radical = 0.0

    # QSSA closure metrics accumulators
    species_list = None
    species_max_abs: dict[str, float] = {}
    species_max_rel: dict[str, float] = {}
    tested_qssa_intervals = 0

    print("\n[1/5] Streaming parquet files & performing on-the-fly audit...")
    for idx, pf in enumerate(parquet_files, 1):
        df_part = pd.read_parquet(pf)
        n_part_rows = len(df_part)
        total_rows += n_part_rows

        # Termination reasons
        if "termination_reason" in df_part.columns:
            terms = df_part[df_part["termination_reason"] != ""]["termination_reason"].value_counts()
            for k, v in terms.items():
                termination_counts[k] = termination_counts.get(k, 0) + int(v)

        # Strata
        if "stratum_name" in df_part.columns:
            strata = df_part["stratum_name"].value_counts()
            for k, v in strata.items():
                stratum_counts[k] = stratum_counts.get(k, 0) + int(v)

        # Trajectory unique keys
        if "sample_id" in df_part.columns:
            mechanism_values = (
                df_part["mechanism_name"].astype(str)
                if "mechanism_name" in df_part.columns
                else pd.Series(pf.parent.name.replace("trajectories_", ""), index=df_part.index)
            )
            trajectories_seen.update(
                zip(mechanism_values.tolist(), df_part["sample_id"].astype(str).tolist())
            )

        # State non-negativity
        state_columns = [
            c for c in df_part.columns
            if (c.startswith("Y_") or c.startswith("Y_next_"))
        ]
        if state_columns:
            state_values = df_part[state_columns].to_numpy(dtype=np.float64, copy=False)
            negative_state_count += int((state_values < -negative_tolerance).sum())

        # Pressure range
        if "P" in df_part.columns:
            p_min_overall = min(p_min_overall, float(df_part["P"].min()))
            p_max_overall = max(p_max_overall, float(df_part["P"].max()))

        # Cold oxidation initial radicals at t=0
        if "stratum_name" in df_part.columns and "time" in df_part.columns:
            m_cold = df_part[(df_part["stratum_name"] == "Spec_Cold_Oxidation") & (df_part["time"] == 0.0)]
            if len(m_cold) > 0 and "initial_radical_total" in m_cold.columns:
                cold_t0_count += len(m_cold)
                cold_t0_max_radical = max(cold_t0_max_radical, float(m_cold["initial_radical_total"].max()))

        # QSSA Exact Algebraic Closure
        if check_all_rows:
            qssa_df = df_part
        else:
            n_sub = max(1, max_check_rows // n_parts)
            qssa_df = df_part.sample(n=min(len(df_part), n_sub), random_state=42)

        tested_qssa_intervals += len(qssa_df)

        if species_list is None:
            y_cols = [c for c in qssa_df.columns if c.startswith("Y_") and not c.startswith("Y_next_")]
            species_list = [c[2:] for c in y_cols]
            for sp in species_list:
                species_max_abs[sp] = 0.0
                species_max_rel[sp] = 0.0

        dt_arr = qssa_df["dt"].to_numpy(dtype=np.float64, copy=False)

        for sp in species_list:
            y0_col = f"Y_{sp}"
            ynext_col = f"Y_next_{sp}"
            p_col = f"P_avg_{sp}"
            d_col = f"D_coef_avg_{sp}"

            if not all(c in qssa_df.columns for c in [y0_col, ynext_col, p_col, d_col]):
                continue

            y0 = qssa_df[y0_col].to_numpy(dtype=np.float64, copy=False)
            y_next = qssa_df[ynext_col].to_numpy(dtype=np.float64, copy=False)
            p_val = qssa_df[p_col].to_numpy(dtype=np.float64, copy=False)
            d_val = qssa_df[d_col].to_numpy(dtype=np.float64, copy=False)

            z = d_val * dt_arr
            safe_z = np.maximum(z, 1e-12)
            phi1 = np.where(
                z < 1e-7,
                1.0 - 0.5 * z + (z**2) / 6.0,
                (1.0 - np.exp(-np.minimum(z, 700.0))) / safe_z,
            )
            exp_z = np.where(z > 700.0, 0.0, np.exp(-z))
            y_rec = y0 * exp_z + p_val * dt_arr * phi1

            abs_err = np.abs(y_rec - y_next)
            sp_max_abs = float(np.max(abs_err))
            species_max_abs[sp] = max(species_max_abs[sp], sp_max_abs)

            active = np.abs(y_next) > relative_floor
            if np.any(active):
                rel_err = abs_err[active] / np.abs(y_next[active])
                sp_max_rel = float(np.max(rel_err))
            else:
                sp_max_rel = 0.0
            species_max_rel[sp] = max(species_max_rel[sp], sp_max_rel)

        # Free part DataFrame memory immediately
        del df_part
        if not check_all_rows:
            del qssa_df

        # Periodic progress logging
        if idx % 20 == 0 or idx == n_parts:
            cur_global_rel = max(species_max_rel.values()) if species_max_rel else 0.0
            print(
                f"  [{idx:3d}/{n_parts}] Audited: {total_rows:11,d} rows | "
                f"Trajectories: {len(trajectories_seen):6,d} | "
                f"Max QSSA Rel: {cur_global_rel:.2e}"
            )
            gc.collect()

    n_trajs = len(trajectories_seen)
    print(f"\n-> Total time-step intervals: {total_rows:,}")
    print(f"-> Total distinct completed trajectories: {n_trajs:,}")
    print(f"-> Negative state values below tolerance: {negative_state_count:,}")
    if negative_state_count > 0:
        print(
            f"  [FAIL] Found negative mass-fraction values below "
            f"-{negative_tolerance:.1e}."
        )
        has_error = True
    else:
        print(f"  [PASS] Zero negative values detected (all states >= -{negative_tolerance:.1e}).")

    print("\n[2/5] Termination Reason Distribution (Guarding Step & Induction Truncation):")
    max_steps_count = termination_counts.get("max_steps", 0)
    for reason, count in sorted(termination_counts.items(), key=lambda x: -x[1]):
        pct = (count / max(n_trajs, 1)) * 100
        print(f"     * {reason:25s}: {count:6d} ({pct:.1f}%)")

    if max_steps_count == 0:
        print("  [PASS] 0 trajectories truncated by step limits. 100% reached physical equilibrium or unignited timeout.")
    else:
        print(f"  [FAIL] {max_steps_count} trajectories hit 'max_steps' before reaching physical equilibrium or unignited timeout!")
        has_error = True

    if stratum_counts:
        print(f"\n-> Stratum distribution (rows):")
        for s_name, count in sorted(stratum_counts.items(), key=lambda x: -x[1]):
            print(f"     * {s_name:25s}: {count:11,d} rows")

    # 4. Pressure Range Audit
    print("\n[3/5] Auditing Pressure range...")
    print(f"-> Pressure range: [{p_min_overall:.4f}, {p_max_overall:.4f}] atm")
    if p_max_overall > max_pressure:
        print(f"  [FAIL] Pressure exceeds {max_pressure:.1f} atm! Check if Pa was passed mistakenly.")
        has_error = True
    elif p_min_overall < 0.01:
        print(f"  [FAIL] Pressure < 0.01 atm! Unphysical vacuum condition.")
        has_error = True
    else:
        print(f"  [PASS] Pressure is within safe physical combustion range (0.01 ~ {max_pressure:.1f} atm).")

    # 5. QSSA Algebraic Closure Audit Summary
    print("\n[4/5] Auditing QSSA Exact Algebraic Closure (Absolute & Relative Error)...")
    if species_list:
        max_qssa_abs = max(species_max_abs.values()) if species_max_abs else 0.0
        max_qssa_rel = max(species_max_rel.values()) if species_max_rel else 0.0
        worst_abs_species = max(species_max_abs, key=species_max_abs.get) if species_max_abs else ""
        worst_rel_species = max(species_max_rel, key=species_max_rel.get) if species_max_rel else ""

        print(
            f"-> Tested {tested_qssa_intervals:,} intervals across {len(species_list)} species "
            f"(relative floor={relative_floor:.1e})."
        )
        print(f"-> Global Max Absolute Residual: {max_qssa_abs:.3e} (worst: {worst_abs_species})")
        print(f"-> Global Max Relative Error:    {max_qssa_rel:.3e} (worst: {worst_rel_species})")

        print("-> Top 5 species by max relative error:")
        top_rel = sorted(species_max_rel.items(), key=lambda x: -x[1])[:5]
        for sp, m_rel in top_rel:
            m_abs = species_max_abs.get(sp, 0.0)
            print(f"     * {sp:15s}: max_abs = {m_abs:.3e}, max_rel = {m_rel:.3e}")

        if max_qssa_abs < 1e-10 and max_qssa_rel < 1e-6:
            print(f"  [PASS] Machine-precision QSSA algebraic closure strictly verified (abs < 1e-10, rel < 1e-6)!")
        else:
            print(f"  [FAIL] QSSA closure exceeded tolerance: abs={max_qssa_abs:.3e}, rel={max_qssa_rel:.3e}")
            has_error = True

    # 6. Cold Oxidation Initial Radicals Audit
    print("\n[5/5] Auditing Cold Oxidation initial radical baseline...")
    if cold_t0_count > 0:
        print(f"-> Audited {cold_t0_count:,} Spec_Cold_Oxidation trajectories at t=0:")
        print(f"   Max initial_radical_total: {cold_t0_max_radical:.3e}")
        if cold_t0_max_radical < 1e-15:
            print(f"  [PASS] Cold oxidation initial radicals are strictly zero.")
        else:
            print(f"  [FAIL] Cold oxidation initial radicals are non-zero: {cold_t0_max_radical:.3e}")
            has_error = True
    else:
        print("-> (No Spec_Cold_Oxidation trajectories found at t=0)")

    print("\n" + "=" * 78)
    if has_error:
        print("[AUDIT RESULT] DATABASE FAILED QUALITY GATES (Exit code 1)")
        print("=" * 78)
        sys.exit(1)
    else:
        print("[AUDIT RESULT] DATABASE PASSED ALL QUALITY GATES STRICTLY (Exit code 0)")
        print("=" * 78)
        sys.exit(0)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Audit Generated Transient Database for Phase 3 Integrity")
    parser.add_argument("database_dir", type=str, help="Path to database directory containing parquet files")
    parser.add_argument("--max_rows", type=int, default=20000, help="Max sample rows for QSSA closure test")
    parser.add_argument(
        "--all",
        dest="check_all_rows",
        action="store_true",
        default=True,
        help="Audit all rows across the entire database (default, streaming low-memory)",
    )
    parser.add_argument(
        "--sample",
        dest="check_all_rows",
        action="store_false",
        help="Use a bounded sample for QSSA closure instead of all rows",
    )
    parser.add_argument(
        "--relative-floor",
        type=float,
        default=1e-40,
        help="Smallest absolute state included in relative QSSA error checks",
    )
    parser.add_argument(
        "--negative-tolerance",
        type=float,
        default=1e-40,
        help="Allowed negative mass-fraction round-off before failing",
    )
    parser.add_argument(
        "--min-success-rate",
        type=float,
        default=90.0,
        help="Minimum required trajectory success rate percentage (default: 90.0)",
    )
    parser.add_argument(
        "--max-pressure",
        type=float,
        default=1000.0,
        help="Upper pressure boundary in atm to allow constant-volume ignition peaks while flagging Pa (default: 1000.0)",
    )
    args = parser.parse_args()

    audit_database(
        args.database_dir,
        max_check_rows=args.max_rows,
        check_all_rows=args.check_all_rows,
        relative_floor=args.relative_floor,
        negative_tolerance=args.negative_tolerance,
        min_success_rate=args.min_success_rate,
        max_pressure=args.max_pressure,
    )
